import { getVersion } from "./version.js";
import type { Finding, ScanResult, ScanSummary } from "./types.js";

export function formatJson(result: ScanResult): string {
  return JSON.stringify(
    {
      tool: "arcgis-migrate",
      version: getVersion(),
      generatedAt: new Date().toISOString(),
      summary: result.summary,
      findings: result.findings,
    },
    null,
    2,
  );
}

export function formatMarkdown(result: ScanResult): string {
  const { summary, findings } = result;
  const lines: string[] = [];

  lines.push("# ArcGIS migration scan");
  lines.push("");
  lines.push(
    `Scanned **${summary.filesScanned}** file${plural(summary.filesScanned)} in ${(
      summary.durationMs / 1000
    ).toFixed(2)}s.`,
  );
  lines.push("");

  if (findings.length === 0) {
    lines.push("No widget-era patterns found. This project looks component-ready.");
    lines.push("");
    lines.push("---");
    lines.push("");
    lines.push("Generated by `arcgis-migrate`.");
    return lines.join("\n");
  }

  lines.push(
    `Found **${summary.total}** finding${plural(summary.total)} in **${summary.filesWithFindings}** file${plural(
      summary.filesWithFindings,
    )}: **${summary.errors}** errors, **${summary.warnings}** warnings, **${summary.info}** info.`,
  );
  lines.push("");
  lines.push(`Estimated effort: **~${summary.effortHours}h** (rough).`);
  lines.push("");

  lines.push("## Findings by rule");
  lines.push("");
  lines.push("| Rule | Severity | Count | Est. hours |");
  lines.push("| --- | --- | ---: | ---: |");
  for (const [ruleId, items] of groupBy(findings, (finding) => finding.ruleId)) {
    const first = items[0]!;
    const hours = Math.round(items.reduce((total, item) => total + item.effortHours, 0) * 100) / 100;
    lines.push(`| \`${ruleId}\` | ${first.severity} | ${items.length} | ${hours} |`);
  }
  lines.push("");

  lines.push("## Findings by file");
  for (const [file, items] of groupBy(findings, (finding) => finding.file)) {
    lines.push("");
    lines.push(`### \`${file}\``);
    lines.push("");
    for (const finding of items) {
      lines.push(
        `- **${finding.severity.toUpperCase()}** \`${finding.ruleId}\` — ${finding.message} (line ${finding.line}, col ${finding.column})`,
      );
      if (finding.suggestion) lines.push(`  - ${finding.suggestion}`);
      if (finding.snippet) {
        lines.push(`  - \`${finding.snippet.replace(/`/g, "'")}\``);
      }
    }
  }

  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push(
    "Generated by `arcgis-migrate`. Review each finding; dynamic code, custom wrappers, and view models may need manual migration.",
  );

  return lines.join("\n");
}

export function formatSummaryLine(summary: ScanSummary): string {
  return `${summary.total} findings in ${summary.filesWithFindings} files (${summary.errors} errors, ${summary.warnings} warnings, ${summary.info} info, ~${summary.effortHours}h)`;
}

function groupBy<T>(items: T[], keyFn: (item: T) => string): Map<string, T[]> {
  const groups = new Map<string, T[]>();
  for (const item of items) {
    const key = keyFn(item);
    const group = groups.get(key);
    if (group) group.push(item);
    else groups.set(key, [item]);
  }
  return new Map([...groups.entries()].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0])));
}

function plural(count: number): string {
  return count === 1 ? "" : "s";
}

export type { Finding, ScanResult, ScanSummary };
